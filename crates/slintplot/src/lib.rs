//! Native, interactive charts for [Slint](https://slint.dev).
//!
//! Charts are drawn with Slint's own `Path`, `Rectangle` and `Text` elements, so
//! they stay sharp at any scale, follow the theme and react to the mouse. The
//! math (scales, ticks, path generation) lives in this crate and is exposed to
//! Slint through the `ChartEngine` global, which [`register!`] wires up.
//!
//! # Setup
//!
//! `build.rs`:
//! ```ignore
//! let config = slint_build::CompilerConfiguration::new().with_library_paths(
//!     std::collections::HashMap::from([("slintplot".into(), slintplot::library_path())]),
//! );
//! slint_build::compile_with_config("ui/app.slint", config).unwrap();
//! ```
//!
//! `ui/app.slint`:
//! ```slint,ignore
//! import { LineChart, ChartEngine } from "@slintplot";
//! export { ChartEngine } // must be exported so Rust can register it
//!
//! export component App inherits Window {
//!     LineChart {
//!         labels: ["Jan", "Feb", "Mar"];
//!         datasets: [{ label: "Sales", values: [3, 7, 4], tension: 0.4 }];
//!     }
//! }
//! ```
//!
//! `main.rs`:
//! ```ignore
//! slint::include_modules!();
//! let app = App::new()?;
//! slintplot::register!(app);
//! app.run()
//! ```

